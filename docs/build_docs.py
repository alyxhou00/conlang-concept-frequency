r"""Build docs/*.md from the templates in docs/src/ and a released lexicon version.

Placeholders in the templates:
  {{version}}            the lexicon version, e.g. 0.1.0
  {{w: I SEE DOG}}       the words, in italics: *ö rö tön*
  {{ipa: I SEE DOG}}     the IPA: [ʔø ʁø tøn]
  {{h: DIGNITY}}         the words with syllable breaks, in italics: *et-nöh*
  {{name: SHORT LANGUAGE}}  a proper name: the words capitalized, in italics: *Ihöt Önre*
  {{stats}}              table of counts and average word length
  {{top: 30}}            table of the 30 most frequent words
  {{text: texts/x.txt}}  a concept-tagged text: words, IPA and glosses
  \{{w: ...}}            stays as the literal text {{w: ...}}

Concepts are written as in texts/ (gloss with _ for spaces, or #ID).
Because the docs come from a released version, they only change when a new
version is released.

Run:    .venv/Scripts/python -X utf8 docs/build_docs.py            (latest version)
Check:  .venv/Scripts/python -X utf8 docs/build_docs.py --check    (exit 1 if docs are out of date)
"""
import argparse
import json
import re
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "pipeline"))
from phonetics import pronounce  # noqa: E402
from render import Lexicon, render_line, render_text  # noqa: E402

SRC, OUT, LEXICON_DIR = ROOT / "docs/src", ROOT / "docs", ROOT / "lexicon"
PLACEHOLDER = re.compile(r"(?<!\\)\{\{\s*(\w+)\s*(?::\s*(.*?))?\s*\}\}")  # \{{ ... }} stays literal


def versions():
    """Released versions, oldest first (pre-releases sort before their release)."""
    def key(v):
        core, _, pre = v.partition("-")
        return tuple(int(x) for x in core.split(".")), pre == "", pre
    return sorted((p.stem for p in LEXICON_DIR.glob("*.tsv")), key=key)


class Builder:
    def __init__(self, version):
        self.version = version
        self.lexicon = Lexicon(LEXICON_DIR / f"{version}.tsv")
        self.table = pd.read_csv(LEXICON_DIR / f"{version}.tsv", sep="\t", keep_default_na=False, na_values=[""])
        self.meta = json.loads((LEXICON_DIR / f"{version}.json").read_text(encoding="utf-8"))

    def words(self, tokens):
        return render_line(tokens, self.lexicon)[0]

    def ipa(self, tokens):
        return render_line(tokens, self.lexicon)[1]

    def hyphenated(self, tokens):
        return " ".join(self.lexicon.lookup(t).word_hyphenated for t in tokens.split())

    def stats(self):
        m = self.meta
        per = m["words_per_syllables"]
        free = {k: v for k, v in m["free_slots_per_syllables"].items() if v}
        return "\n".join([
            "| | |", "| --- | --- |",
            f"| Concepts | {m['concepts']:,} |",
            f"| With their own word | {m['own_words']:,} |",
            f"| Said with another concept's word (pronouns) | {m['merged']:,} |",
            f"| Said with existing words (compounds) | {m['compounds']:,} |",
            "| Words with " + " / ".join(per) + " syllables | " + " / ".join(f"{v:,}" for v in per.values()) + " |",
            f"| Average word, weighted by use | {m['average_syllables']:.2f} syllables, {m['average_letters']:.2f} letters |",
            "| Free slots for new words | " + ", ".join(f"{v:,} with {k} syllables" for k, v in free.items()) + " |",
        ])

    def top(self, n):
        rows = self.table[self.table.kind == "word"].sort_values("rank").head(int(n))
        lines = ["| # | Concept | Word | IPA |", "| --- | --- | --- | --- |"]
        lines += [f"| {int(r.rank)} | {r.gloss} | {r.word} | [{pronounce([r.word])[0]}] |" for r in rows.itertuples()]
        return "\n".join(lines)

    def text(self, path):
        blocks = []
        for comments, words, ipa, glosses in render_text((ROOT / path).read_text(encoding="utf-8"), self.lexicon):
            quote = "".join(f"> {c}\n" for c in comments)
            blocks.append(f"{quote}\n**{words}**  \n[{ipa}]  \n{glosses}")
        return "\n\n".join(blocks)

    def fill(self, template, name):
        def one(m):
            kind, arg = m.group(1), m.group(2)
            if kind == "version":
                return self.version
            if kind == "w":
                return f"*{self.words(arg)}*"
            if kind == "ipa":
                return f"[{self.ipa(arg)}]"
            if kind == "name":
                return "*" + " ".join(w.capitalize() for w in self.words(arg).split()) + "*"
            if kind == "h":
                return f"*{self.hyphenated(arg)}*"
            if kind == "stats":
                return self.stats()
            if kind == "top":
                return self.top(arg)
            if kind == "text":
                return self.text(arg)
            raise ValueError(f"{name}: unknown placeholder {m.group(0)}")
        header = (f"<!-- Generated by docs/build_docs.py from docs/src/{name} and lexicon/{self.version}.tsv. "
                  "Edit the source, not this file. -->\n")
        return header + PLACEHOLDER.sub(one, template).replace("\\{{", "{{")


def build(version=None):
    """{output path: content} for every template."""
    version = version or versions()[-1]
    b = Builder(version)
    return {OUT / src.name: b.fill(src.read_text(encoding="utf-8"), src.name) for src in sorted(SRC.glob("*.md"))}


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--version", help="lexicon version (default: the latest in lexicon/)")
    ap.add_argument("--check", action="store_true", help="only report docs that are out of date")
    args = ap.parse_args()

    stale = []
    for path, content in build(args.version).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(path.name)
            if not args.check:
                path.write_text(content, encoding="utf-8")
    if args.check:
        print("out of date: " + ", ".join(stale) if stale else "docs are up to date")
        sys.exit(1 if stale else 0)
    print(f"updated {len(stale)} file(s)" + (": " + ", ".join(stale) if stale else ""))


if __name__ == "__main__":
    main()
